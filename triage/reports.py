"""The invented reports: load them, attach a test photo to each, and render each report as a Markdown file.

`reports/reports.json` holds the 36 reports: the form fields the call-taker or the app records, and the reporter's
description. Each report names the kind of test photo attached to it; this module draws the photos once, with a fixed
seed, from the image sets the photo reader is tested on, and records where each came from in `reports/photos.csv`:

- `ctx`: a CTX-UXO crop from the test split, never used in training (category known);
- `ctx_hidden_25`, `ctx_hidden_40`: the same kind of crop with a grey square over 25% or 40% of it, as in P4;
- `left_out`: a crop of one of the seven CTX-UXO categories the reader never trained on;
- `background`: a crop of ground with no item (SULAND, from P5);
- `generated`: an image generated by P5's GAN, marked as generated;
- `none`: no photo.

Build from the repository root:  python -m triage.reports
"""
import io
import json
import math
import zipfile
from pathlib import Path

import numpy as np
import pandas as pd
from PIL import Image

from triage import generated_images, photo_reader

REPORTS_DIR = Path("reports")
REPORTS_JSON = REPORTS_DIR / "reports.json"
PHOTOS_CSV = REPORTS_DIR / "photos.csv"
PHOTOS_DIR = REPORTS_DIR / "photos"
PHOTO_SEED = 7
FORM_FIELDS = [("received", "Received"), ("channel", "Channel"), ("reporter", "Reporter"),
               ("municipality", "Municipality"), ("place", "Place"), ("place_type", "Type of place"),
               ("people_close", "People close to the item"), ("children", "Children"),
               ("moved", "Item moved"), ("condition", "Condition of the item"),
               ("controllable", "Area can be evacuated and cordoned off"), ("marked", "Marked"),
               ("photo_status", "Photo")]


def load_reports(path=REPORTS_JSON):
    return json.loads(Path(path).read_text(encoding="utf-8"))["reports"]


def hide_square(image, share, rng, fill):
    """One square covering `share` of an 8-bit crop, filled with the training images' average colour (as in P4)."""
    out = image.copy()
    side = round(image.shape[0] * math.sqrt(share))
    top, left = rng.integers(0, image.shape[0] - side + 1), rng.integers(0, image.shape[1] - side + 1)
    out[top:top + side, left:left + side] = fill
    return out


def draw_photos(reports, data_dir=photo_reader.DATA_DIR):
    """Draw one test image per report that has a photo; return {report id: 8-bit image} and the provenance table."""
    rng = np.random.default_rng(PHOTO_SEED)
    data = photo_reader.load_crop_data(data_dir)
    crops = data.crops
    fill = np.round(data.channel_mean.numpy() * 255).astype(np.uint8)
    test_rows = data.rows["test"]
    background_manifest, background = photo_reader.load_background(data_dir)
    generated_manifest, generated = generated_images.load_generated(data_dir)
    used = set()
    images, records = {}, []

    def pick(pool):
        choice = int(rng.choice([i for i in pool if i not in used]))
        used.add(choice)
        return choice

    for report in reports:
        kind = report["photo"]
        if kind == "none":
            records.append({"report": report["id"], "kind": kind, "source": "", "truth": "no photo", "hidden_share": 0.0})
            continue
        if kind.startswith("ctx"):
            row = pick(test_rows)
            image, share = data.images[row], 0.0
            if kind.startswith("ctx_hidden"):
                share = int(kind.rsplit("_", 1)[1]) / 100
                image = hide_square(image, share, rng, fill)
            source, truth = f"CTX-UXO test crop {crops.crop_file.iloc[row]}", crops.category.iloc[row]
        elif kind == "left_out":
            row = pick(data.unseen_rows)
            image, share = data.images[row], 0.0
            source, truth = f"CTX-UXO crop {crops.crop_file.iloc[row]}", f"left-out category: {crops.category.iloc[row]}"
        elif kind == "background":
            i = int(rng.integers(len(background)))
            image, share = background[i], 0.0
            source, truth = f"SULAND background crop {background_manifest.file.iloc[i]}", "no item"
        elif kind == "generated":
            i = int(rng.integers(len(generated)))
            image, share = generated[i], 0.0
            source, truth = f"GENERATED by P5's GAN: {generated_manifest.file.iloc[i]}", "generated image"
        else:
            raise ValueError(f"{report['id']}: unknown photo kind {kind!r}")
        images[report["id"]] = image
        records.append({"report": report["id"], "kind": kind, "source": source, "truth": truth, "hidden_share": share})
    return images, pd.DataFrame(records)


def photo_status(report):
    return "none" if report["photo"] == "none" else "attached, taken from where the reporter stood"


def render(report):
    """One report as Markdown, with a fixed set of sections, so the agent can read it section by section."""
    rows = [f"| {label} | {report['municipality'] if key == 'municipality' else photo_status(report) if key == 'photo_status' else report[key]} |"
            for key, label in FORM_FIELDS]
    return "\n".join([
        f"# Report {report['id']}", "",
        "## Form", "",
        "| Field | Answer |", "|---|---|", *rows, "",
        "## Description", "",
        "The reporter's words, in English:", "",
        f"> {report['description']}", "",
    ])


def build(reports_dir=REPORTS_DIR, data_dir=photo_reader.DATA_DIR):
    reports = load_reports(Path(reports_dir) / "reports.json")
    ids = [r["id"] for r in reports]
    assert len(ids) == len(set(ids)), "a report ID appears twice"
    images, photos = draw_photos(reports, data_dir)
    photos_dir = Path(reports_dir) / "photos"
    photos_dir.mkdir(parents=True, exist_ok=True)
    for report_id, image in images.items():
        Image.fromarray(image).save(photos_dir / f"{report_id}.png")   # lossless, so the reader sees the same pixels
    photos.to_csv(Path(reports_dir) / "photos.csv", index=False, lineterminator="\n")
    for report in reports:
        (Path(reports_dir) / f"{report['id']}.md").write_text(render(report), encoding="utf-8")
    return reports, photos


def load_photo(report_id, reports_dir=REPORTS_DIR):
    """The report's photo as an 8-bit array (64, 64, 3), or None when the report has none."""
    path = Path(reports_dir) / "photos" / f"{report_id}.png"
    return np.array(Image.open(path).convert("RGB")) if path.exists() else None   # a writable copy


if __name__ == "__main__":
    reports, photos = build()
    print(f"{len(reports)} reports rendered; photos:")
    print(photos.kind.value_counts().to_string())
